// CSATTTL is how long a satisfaction link stays valid.
const CSATTTL = 30 * 24 * time.Hour

// requestCSAT sends the satisfaction survey when a ticket is solved and the workspace
// has CSAT enabled. The token is stored hashed; the email carries it once.
func requestCSAT(ctx context.Context, tx pgx.Tx, d *deps.Deps, wid, tid uuid.UUID) error {
	s, err := hd.LoadSettings(ctx, tx, wid)
	if err != nil || !s.CSATEnabled {
		return err
	}
	var email *string
	var score *int16
	var requested *time.Time
	var spam bool
	var number int64
	var subject string
	var look csatLook
	var logo string
	err = tx.QueryRow(ctx, `SELECT c.email, t.csat_score, t.csat_requested_at, t.spam, t.number, t.subject, w.name,
			COALESCE(tm.name, ''), COALESCE(b.name, ''), COALESCE(b.color, ''), COALESCE(b.images->>'logo', '')
		FROM tickets t JOIN workspaces w ON w.id = t.workspace_id
		LEFT JOIN teams tm ON tm.id = t.team_id AND tm.workspace_id = t.workspace_id
		LEFT JOIN brands b ON b.id = t.brand_id AND b.workspace_id = t.workspace_id
		LEFT JOIN contacts c ON c.id = t.contact_id
		WHERE t.workspace_id = $1 AND t.id = $2`, wid, tid).Scan(&email, &score, &requested, &spam, &number, &subject, &look.workspace,
		&look.team, &look.brand, &look.color, &logo)
	if err != nil {
		return err
	}
	if look.color == "" {
		look.color = s.BrandColor
	}
	look.logoURL = domain.Avatar(logo).URL()
	// One survey per ticket a day; rated, spam and contactless tickets get none.
	if email == nil || *email == "" || score != nil || spam || (requested != nil && time.Since(*requested) < 24*time.Hour) {
		return nil
	}
	token := crypto.RandomToken(32)
	if _, err := tx.Exec(ctx, `UPDATE tickets SET csat_token_hash = $3, csat_requested_at = now() WHERE workspace_id = $1 AND id = $2`,
		wid, tid, crypto.HashToken(token)); err != nil {
		return err
	}
	mail := csatEmail(d.Cfg.AppURL, token, look, number, subject)
	_, err = d.Jobs.InsertTx(ctx, tx, mail.withTicket(wid, tid), &river.InsertOpts{Queue: jobs.QueueEmail, MaxAttempts: 5})
	return err
}

type csatMail struct{ subject, html, text string }

func (m csatMail) withTicket(wid, tid uuid.UUID) jobs.SendTicketEmailArgs {
	return jobs.SendTicketEmailArgs{WorkspaceID: wid, TicketID: tid, Subject: m.subject, HTML: m.html, Text: m.text, AutoGenerated: true}
}

// csatScoreLabels name the five scores, the same words as the survey page
// (web public.json csat.scores).
var csatScoreLabels = [6]string{"", "Very poor", "Poor", "Okay", "Good", "Great"}

var csatHexColor = regexp.MustCompile(`^#[0-9a-fA-F]{6}$`)

// csatLook is who the survey asks about and how it looks: the ticket's team, else
// its brand, with the brand's colour (else the workspace's) and logo
// (contracts/teams.md).
type csatLook struct {
	team, brand, workspace string
	color, logoURL         string
}

// name is what "How did <name> do?" names: the team, else the brand, else the workspace.
func (l csatLook) name() string {
	for _, n := range []string{l.team, l.brand, l.workspace} {
		if n = strings.TrimSpace(n); n != "" {
			return n
		}
	}
	return "we"
}

// csatEmail is a short message with five score links in the brand's colour.
func csatEmail(appURL, token string, look csatLook, number int64, subject string) csatMail {
	base := strings.TrimRight(appURL, "/") + "/csat/" + token + "?score="
	accent := "#0A0A0A"
	if csatHexColor.MatchString(look.color) {
		accent = look.color
	}
	var links, text strings.Builder
	for n := 1; n <= 5; n++ {
		u := base + strconv.Itoa(n)
		fmt.Fprintf(&links, `<td style="padding:0 4px"><a href="%s" title="%s" style="display:inline-block;width:44px;height:44px;line-height:42px;border:2px solid %s;border-radius:8px;color:#0A0A0A;text-decoration:none;font-weight:600;font-size:16px;text-align:center">%d</a></td>`,
			html.EscapeString(u), csatScoreLabels[n], accent, n)
		fmt.Fprintf(&text, "%d (%s): %s\n", n, csatScoreLabels[n], u)
	}
	who := look.name()
	name := html.EscapeString(who)
	subj := html.EscapeString(hd.Truncate(subject, 120))
	logo := ""
	if look.logoURL != "" {
		alt := look.brand
		if alt == "" {
			alt = look.workspace
		}
		logo = `<img src="` + html.EscapeString(look.logoURL) + `" alt="` + html.EscapeString(alt) + `" height="32" style="display:block;height:32px;width:auto;max-width:200px;border:0;margin:0 0 16px">`
	}
	body := `<!doctype html><html><body style="margin:0;padding:24px;background:#FFFFFF;color:#0A0A0A;font-family:-apple-system,Segoe UI,Helvetica,Arial,sans-serif">` +
		`<div style="max-width:480px;margin:0 auto">` + logo +
		`<p style="font-size:15px;line-height:22px;margin:0 0 8px">How did ` + name + ` do?</p>` +
		`<p style="font-size:13px;line-height:20px;color:#525252;margin:0 0 20px">Your request #` + strconv.FormatInt(number, 10) + ` &ldquo;` + subj + `&rdquo; was marked solved. Rate it from 1 (very poor) to 5 (great).</p>` +
		`<table role="presentation" cellpadding="0" cellspacing="0" style="border-collapse:collapse"><tr>` + links.String() + `</tr></table>` +
		`<p style="font-size:12px;line-height:18px;color:#8A8A8A;margin:20px 0 0">One click records your answer. You can add a comment on the next page.</p>` +
		`</div></body></html>`
	return csatMail{
		subject: fmt.Sprintf("How did we do? [#%d]", number),
		html:    body,
		text: fmt.Sprintf("How did %s do?\n\nYour request #%d \"%s\" was marked solved. Rate it from 1 (very poor) to 5 (great):\n\n%s",
			who, number, hd.Truncate(subject, 120), text.String()),
	}
}

// CSATView is what the public survey page shows.
type CsatSurvey struct {
	WorkspaceName string `json:"workspace_name"`
	BrandColor    string `json:"brand_color"`
	Ticket        struct {
		Number  int64  `json:"number"`
		Subject string `json:"subject"`
	} `json:"ticket"`
	Score   *int   `json:"score"`
	Comment string `json:"comment"`
	Locale  string `json:"locale" doc:"Workspace default language (BCP 47), empty when not set"`
}

type csatRow struct {
	wid, tid uuid.UUID
	view     CsatSurvey
}

func loadCSAT(ctx context.Context, q db.Querier, token string, lock bool) (csatRow, error) {
	var r csatRow
	var score *int16
	var requested *time.Time
	var settings []byte
	if len(token) < 20 || len(token) > 100 {
		return r, httpx.NotFound("Survey")
	}
	sql := `SELECT t.workspace_id, t.id, t.number, t.subject, t.csat_score, t.csat_comment, t.csat_requested_at, w.name, w.settings
		FROM tickets t JOIN workspaces w ON w.id = t.workspace_id
		WHERE t.csat_token_hash = $1 AND t.deleted_at IS NULL`
	if lock {
		sql += ` FOR UPDATE OF t`
	}
	err := q.QueryRow(ctx, sql, crypto.HashToken(token)).Scan(&r.wid, &r.tid, &r.view.Ticket.Number, &r.view.Ticket.Subject,
		&score, &r.view.Comment, &requested, &r.view.WorkspaceName, &settings)
	if db.IsNotFound(err) || (err == nil && (requested == nil || time.Since(*requested) > CSATTTL)) {
		return r, httpx.NotFound("Survey")
	}
	if err != nil {
		return r, err
	}
	st := hd.ParseSettings(settings)
	r.view.BrandColor, r.view.Locale = st.BrandColor, st.Locale
	if score != nil {
		v := int(*score)
		r.view.Score = &v
	}
	return r, nil
}

type ipKey struct{}

// clientIPMiddleware puts the caller's address in the context for public rate limits.
func clientIPMiddleware(d *deps.Deps) func(huma.Context, func(huma.Context)) {
	ipOf := httpx.ClientIP(d.Cfg.TrustProxy)
	return func(ctx huma.Context, next func(huma.Context)) {
		r, _ := humachi.Unwrap(ctx)
		next(huma.WithValue(ctx, ipKey{}, ipOf(r)))
	}
}

func clientIP(ctx context.Context) string { s, _ := ctx.Value(ipKey{}).(string); return s }

func registerCSAT(d *deps.Deps, api huma.API) {
	mw := huma.Middlewares{clientIPMiddleware(d)}
	huma.Register(api, huma.Operation{OperationID: "get-csat", Method: http.MethodGet, Path: "/v1/public/csat/{token}",
		Summary: "Get a satisfaction survey", Tags: []string{"Public"}, Security: []map[string][]string{}, Middlewares: mw},
		func(ctx context.Context, in *struct {
			Token string `path:"token"`
		}) (*struct{ Body CsatSurvey }, error) {
			if !d.Limiter.Allow("csat:"+clientIP(ctx), 60, time.Minute) {
				return nil, httpx.RateLimited()
			}
			r, err := loadCSAT(ctx, d.DB.Pool, in.Token, false)
			if err != nil {
				return nil, httpx.Wrap(err)
			}
			return &struct{ Body CsatSurvey }{r.view}, nil
		})

	type csatAnswerBody struct {
		Score   int    `json:"score" minimum:"1" maximum:"5"`
		Comment string `json:"comment,omitempty" maxLength:"2000"`
	}
	huma.Register(api, huma.Operation{OperationID: "submit-csat", Method: http.MethodPost, Path: "/v1/public/csat/{token}",
		Summary: "Answer a satisfaction survey", Tags: []string{"Public"}, Security: []map[string][]string{}, Middlewares: mw},
		func(ctx context.Context, in *struct {
			Token string `path:"token"`
			Body  csatAnswerBody
		}) (*struct{ Body CsatSurvey }, error) {
			if !d.Limiter.Allow("csat:"+clientIP(ctx), 30, time.Minute) {
				return nil, httpx.RateLimited()
			}
			comment := strings.TrimSpace(hd.HTMLToText(in.Body.Comment))
			var out CsatSurvey
			err := d.DB.Tx(ctx, func(tx pgx.Tx) error {
				r, err := loadCSAT(ctx, tx, in.Token, true)
				if err != nil {
					return err
				}
				if _, err := tx.Exec(ctx, `UPDATE tickets SET csat_score = $3, csat_comment = $4, updated_at = now()
					WHERE workspace_id = $1 AND id = $2`, r.wid, r.tid, in.Body.Score, comment); err != nil {
					return err
				}
				prev := r.view.Score
				if prev == nil || *prev != in.Body.Score || r.view.Comment != comment {
					data := map[string]any{"score": in.Body.Score}
					if comment != "" {
						data["comment"] = comment
					}
					if _, err := domain.LogActivity(ctx, tx, r.wid, r.tid, "contact", nil, "csat_received", data); err != nil {
						return err
					}
					if err := domain.PublishTicketUpdated(ctx, tx, r.wid, r.tid, []string{"csat"}); err != nil {
						return err
					}
				}
				out = r.view
				out.Score, out.Comment = &in.Body.Score, comment
				return nil
			})
			if err != nil {
				return nil, httpx.Wrap(err)
			}
			return &struct{ Body CsatSurvey }{out}, nil
		})
}
